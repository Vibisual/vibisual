import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { homedir } from 'node:os';

const root = dirname(fileURLToPath(import.meta.url));
const crate = join(root, 'rust');
const output = join(root, 'src/generated/wasmBytes.ts');
const stamp = join(root, 'rust/target/source.sha256');
const inputs = ['Cargo.toml', 'Cargo.lock', 'rust-toolchain.toml', ...readdirSync(join(crate, 'src')).filter(n => n.endsWith('.rs')).sort().map(n => `src/${n}`)];
const fingerprint = () => {
  const hash = createHash('sha256').update(readFileSync(fileURLToPath(import.meta.url)));
  for (const file of inputs) { hash.update(file); if (existsSync(join(crate, file))) hash.update(readFileSync(join(crate, file))); }
  return hash.digest('hex');
};
const before = fingerprint();
if (existsSync(output) && existsSync(stamp) && readFileSync(stamp, 'utf8') === before) {
  process.exit(0);
}

const env = { ...process.env };
let cargo = env.VIBISUAL_RUST_CARGO || env.CARGO || 'cargo';
if (!env.VIBISUAL_RUST_CARGO && !env.CARGO) {
  const suffix = process.platform === 'win32' ? '.exe' : '';
  const standard = join(env.CARGO_HOME || join(homedir(), '.cargo'), 'bin', `cargo${suffix}`);
  if (existsSync(standard)) cargo = standard;
  else if (process.platform === 'win32' && env.LOCALAPPDATA) {
    // Optional isolated developer toolchain; neither the application nor CI needs this directory.
    const isolated = join(env.LOCALAPPDATA, 'VibisualBuildTools');
    const candidate = join(isolated, 'cargo/bin/cargo.exe');
    if (existsSync(candidate)) {
      cargo = candidate;
      env.CARGO_HOME = join(isolated, 'cargo');
      env.RUSTUP_HOME = join(isolated, 'rustup');
    }
  }
}
const result = spawnSync(cargo, ['build', '--release', '--target', 'wasm32-unknown-unknown', '--target-dir', join(crate, 'target'), ...(existsSync(join(crate, 'Cargo.lock')) ? ['--locked'] : [])], {
  cwd: crate, env, stdio: 'inherit', windowsHide: true,
});
if (result.error || result.status !== 0) {
  console.error('Rust compute build failed. Install the pinned Rust toolchain and wasm32-unknown-unknown target; see packages/compute/README.md.');
  if (result.error) console.error(result.error.message);
  process.exit(result.status || 1);
}
const wasm = readFileSync(resolve(crate, 'target/wasm32-unknown-unknown/release/vibisual_compute.wasm'));
if (!WebAssembly.validate(wasm)) throw new Error('Rust compiler emitted an invalid WebAssembly module');
mkdirSync(dirname(output), { recursive: true });
writeFileSync(output, `// Generated by packages/compute/build.mjs. Rebuild from Rust sources.\nexport const COMPUTE_WASM_BASE64 = '${wasm.toString('base64')}';\n`);
// Use the inputs observed before compilation. A concurrent source edit must
// invalidate the next build instead of blessing an older binary as up-to-date.
writeFileSync(stamp, before);
console.log(`Rust compute: ${wasm.length} bytes, embedded for Node and browser bundles.`);
