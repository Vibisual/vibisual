/**
 * §5.5 #17-6 — **밖에 선 IDE 창의 닫기는 창을 닫는다. 버블로 가는 길은 손잡이 하나뿐이다.** 규칙 단독 소유.
 *
 * 같은 `OverlayShell` 이 그리는 창인데 태어난 길이 둘이다 — (A) 위젯으로 보낸 버블을 더블클릭해
 * 편 IDE, (H-4) 앱 안 IDE 를 밖으로 끌어내서 만든 창. 종전에는 닫기의 뜻을 이 **출신**으로 갈랐다:
 * 위젯 출신은 버블로 접히고(창은 남는다), 끌어낸 창은 앱 안으로 돌아갔다((H-9) `revealInMain` +
 * `closeSelf`). 거기에 (H-18) 이 붙었다 — 타이틀바 [오버레이 버블로 바꾸기]를 한 번 누르면 그 뒤로
 * 이 창의 본체는 버블이라며, 그 다음 닫기도 접기로 갔다(`convertedToBubble` 이 출신을 덮었다).
 *
 * ⚠ **(H-20) 그 갈래를 없앤다.** 사용자 지시 — "이거 누르면 독립된 창이 오버레이 버블이 되는데
 *   여기에 버튼이 생겼으니 독립된 IDE 창을 닫기 누르면 닫히게 만들어". 버블로 줄이는 손잡이가
 *   타이틀바에 섰으니, 닫기까지 버블로 가면 같은 결과로 가는 손잡이가 둘이고 **닫기는 닫기가
 *   아니게 된다**(닫았는데 창이 남는다). 이제 규칙은 하나다:
 *
 *    · **✕ / Esc 는 창을 닫는다** — 출신((A)·(H-4))도, 버블로 바꿨던 이력도 닫기의 뜻을 바꾸지 않는다.
 *    · **버블로 접히는 것은 [오버레이 버블로 바꾸기]를 눌렀을 때뿐이다** — 그 손잡이도 스토어의
 *      `closeIDEOverlay()` 로 접힘을 부르므로(IDE 는 IPC 를 직접 부르지 않는다 — (H-18) ③),
 *      셸이 "이번 접힘은 버블로"라는 표식을 **먼저** 세우고, 접힘을 미러하는 효과가 그 표식을 읽고
 *      **곧바로 내린다**. 한 번짜리다 — 버블을 더블클릭해 다시 편 뒤의 닫기는 도로 닫기다.
 *
 * ⚠ **닫기 전에 앱을 앞으로 끌어올리는 (H-9) 의 예의는 그대로다.** 닫힌 에이전트는 앱 안에만
 *   남으므로 `revealInMain({ openIde: false, keepPanes: true })` 로 앱을 앞에 세우고 카메라를 그
 *   버블에 맞춘 뒤 닫는다(IDE 는 다시 열지 않는다 — 열면 닫기를 두 번 눌러야 닫힌다. `keepPanes` —
 *   앱에서 보고 있던 남의 창도 건드리지 않는다). **받아 주지 못해도 닫는다** — 종전의 물러남(메인
 *   창이 없으면 버블로 접기)은 없앴다. 메인 창이 닫히면 오버레이도 함께 닫히므로(v2.73 사슬) 그
 *   갈래는 실제로 오지 않고, 왔더라도 닫기를 눌렀는데 남는 창이 곧 이 항목이 고친 버그다.
 *
 * 접기로 물러나는 유일한 경우는 **닫는 다리 자체가 없을 때**(`closeSelf` 가 없는 옛 preload)다 —
 * 그때는 접기가 이 창이 할 수 있는 전부다.
 */

/** 닫기를 눌렀을 때 이 창이 할 일. */
export type OverlayCloseIntent =
  /** 버블로 접는다(창은 남는다) — [오버레이 버블로 바꾸기]의 부탁이거나, 닫을 길이 없을 때의 물러남. */
  | 'collapse'
  /** 창을 닫는다(닫기 전에 (H-9) 대로 앱을 앞으로 끌어올린다). */
  | 'close';

export interface OverlayCloseContext {
  /**
   * (H-20) **이번 접힘**이 타이틀바 [오버레이 버블로 바꾸기]에서 왔는가. 셸이 손잡이를 누를 때
   * 세우고 접힘을 미러하는 효과가 읽은 뒤 곧바로 내리는 **한 번짜리** 표식이다 — (H-18) 의
   * `convertedToBubble`(한 번 누르면 내내 참)과 달리 그 뒤의 닫기에는 아무 영향이 없다.
   */
  toBubble: boolean;
  /** 창을 닫는 길이 이 창에 있는가(`window.api.overlay.closeSelf`). 없으면 접기로 물러난다. */
  canCloseSelf: boolean;
}

/**
 * 닫기의 뜻을 정한다. 순수 함수라 세 갈래(버블 부탁·닫기·닫을 길 없음)를 DOM 없이 고정한다.
 * 출신(`initiallyExpanded`)은 입력에 **없다** — 닫기의 뜻을 바꾸지 않는 것은 받지 않는다.
 */
export function resolveOverlayCloseIntent(ctx: OverlayCloseContext): OverlayCloseIntent {
  if (ctx.toBubble) return 'collapse';      // [오버레이 버블로 바꾸기] — 이번 접힘만 버블로
  if (!ctx.canCloseSelf) return 'collapse'; // 닫을 다리가 없다 — 남는 쪽으로 물러난다
  return 'close';                           // ✕ / Esc — 닫는다(출신·이력 무관)
}
