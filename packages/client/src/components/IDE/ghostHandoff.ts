// SCENARIO.md §5.5 #17-6 (H-15) — **선을 걷어 달라는 부탁은 판이 다시 돌아도 살아남는다.**
//
// (H-12) 로 들어오는 길에는 윤곽선(클릭통과 투명 창)이 커서에 매달린 채 서 있고, 앱 안 창이
// 그 자리를 이어받아 **다 그린 뒤에** 스스로 그 선을 걷기로 되어 있다((H-6) ⑤ "선이 있던 자리에
// 창이 채워지므로 선이 창이 된다"). 그런데 그 부탁이 **효과의 정리(cleanup)에 매여** 있었다:
//
//   ① 부탁은 두 프레임 뒤에 나간다(창이 손 아래로 옮겨진 것이 화면에 그려진 뒤).
//   ② 그 두 프레임 안에 효과가 다시 돌면 정리가 예약을 **취소**한다 — 그 효과는 `agent`
//      (`nodeMap[agentId]` — 도는 에이전트라면 스냅샷마다 새 객체다)에 매여 있어 실제로 잦다.
//   ③ 다시 돈 판은 짐(`takePaneDragResume`)을 **이미 꺼내 갔으므로** 곧바로 되돌아간다.
//
// 그래서 "다 그렸다"가 영영 나가지 않고, 사용자가 없앨 수도 없는 윤곽선이 커서에 붙은 채
// 남았다(사용자 보고 — "나갔다가 들어왔는데 가상창이 안 사라지고 마우스에 붙어 있다").
// main 의 그물이 뒤늦게 걷긴 하지만, 그 몇 초 동안 화면 위에 뜬 선은 고장으로 읽힌다.
//
// 예약을 **훅 밖**에 두어 컴포넌트 수명과 끊는다. 늦게 걷는 것은 안전하지만(선은 한 벌뿐이고
// 주인은 main 이 따로 가린다) **안 걷는 것은 안전하지 않다** — 되돌릴 손잡이가 사용자에게 없다.

/**
 * 두 프레임 뒤에 윤곽선을 걷어 달라고 부탁한다 — **취소할 수 없다.**
 *
 * 두 프레임을 기다리는 까닭은 종전과 같다: 부르는 자리는 레이아웃 직후이고, 그 직전에 창이
 * 손 아래로 옮겨졌다 — 그 이동이 화면에 그려지기 전에 선을 걷으면 한 프레임이 빈다.
 *
 * 여러 번 불려도 안전하다(main 의 `hidePopOutGhost` 는 없는 선을 걷어도 조용히 지나간다).
 * 데스크톱 앱이 아니면(오버레이 IPC 없음) 아무 일도 하지 않는다.
 */
export function scheduleGhostHide(): void {
  if (typeof window === 'undefined') return;
  window.requestAnimationFrame(() => {
    window.requestAnimationFrame(() => {
      void window.api?.overlay?.ghostHide?.();
    });
  });
}
